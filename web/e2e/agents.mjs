// Shared by the workspace regression check and the isolated Phase 9 runner.
export async function checkAgents(page, ok) {
  const made = [];
  const json = (path, method = "GET", body) => page.evaluate(async ({ path, method, body }) => {
    const r = await fetch(path, { method, headers: { "content-type": "application/json" }, body: body === undefined ? undefined : JSON.stringify(body) });
    if (!r.ok) throw new Error(`${method} ${path}: ${r.status}`);
    return r.status === 204 ? null : r.json();
  }, { path, method, body });
  const name = `Phase9 ${Date.now()}`;
  const editor = page.getByTestId("agent-editor");
  try {
    await page.getByTestId("nav-agents").click();
    await page.keyboard.press("n");
    const dialog = page.getByRole("dialog", { name: "New agent", exact: true });
    await dialog.waitFor();
    ok(await dialog.getByRole("button", { name: "Create agent" }).isDisabled(), "blank Agent name cannot be created");
    await dialog.getByRole("textbox", { name: "Name", exact: true }).fill(name);
    await dialog.locator("summary").click();
    await dialog.getByLabel("Engine", { exact: true }).selectOption("echo");
    await dialog.getByLabel("Model", { exact: true }).selectOption("echo::echo-1");
    await dialog.getByRole("button", { name: "Create agent" }).click();
    await editor.waitFor();
    const id = await page.evaluate(() => decodeURIComponent(location.hash.split("/")[2])); made.push(id);
    ok(!!(await json("/api/bots")).bots.find((b) => b.id === id)?.cwd, "created Agent has a workspace and opens the editor");
    await editor.getByLabel("Instructions", { exact: true }).fill("Answer the inventory question clearly.");
    await editor.getByLabel("Name", { exact: true }).fill(name + " saved");
    ok(await editor.getByRole("status").innerText() === "Unsaved changes", "editing shows Unsaved changes");
    await editor.getByRole("tab", { name: "Limits", exact: true }).click();
    await editor.getByLabel("Working folder").fill("");
    await editor.getByRole("radio", { name: /^Edits/ }).click();
    await editor.getByRole("tab", { name: "Build", exact: true }).click();
    ok(await editor.getByLabel("Instructions", { exact: true }).inputValue() === "Answer the inventory question clearly.", "switching tabs preserves the draft");
    ok((await json("/api/bots")).bots.find((b) => b.id === id).soul === "", "typing and tab changes do not autosave");
    await page.keyboard.press("Control+s");
    await page.waitForFunction(() => document.querySelector('[role="status"]')?.textContent === "Saved");
    await page.reload({ waitUntil: "networkidle" });
    await editor.waitFor();
    ok(await editor.getByLabel("Name", { exact: true }).inputValue() === name + " saved" && await editor.getByLabel("Instructions", { exact: true }).inputValue() === "Answer the inventory question clearly.", "Save persists both name and instructions after reload");
    await editor.getByLabel("Name", { exact: true }).fill("Discard me");
    await editor.getByRole("button", { name: "Discard", exact: true }).click();
    ok(await editor.getByLabel("Name", { exact: true }).inputValue() === name + " saved", "Discard restores persisted fields");
    await editor.getByLabel("Title", { exact: true }).fill("Pending title");
    page.once("dialog", (d) => d.dismiss());
    await page.getByTestId("nav-dashboard").click();
    ok(await editor.isVisible(), "canceling unsaved navigation keeps the editor");
    await json(`/api/bots/${id}`, "PATCH", { description: "External edit" });
    await editor.getByText("This agent changed elsewhere", { exact: true }).waitFor();
    await editor.getByRole("button", { name: "Keep mine", exact: true }).click();
    await editor.getByRole("button", { name: "Discard", exact: true }).click();
    ok(await editor.getByLabel("Description").inputValue() === "External edit", "external edits are visible and Discard restores the latest server values");
    for (const label of ["Toolbox", "MCP servers", "Limits", "Availability", "Evals", "Knowledge gaps", "History", "Build"]) { await editor.getByRole("tab", { name: label, exact: true }).click(); ok(await editor.getByRole("tabpanel").isVisible(), `${label} tab is reachable`); }
    await editor.getByRole("tab", { name: "Toolbox", exact: true }).click();
    const gallery = editor.getByTestId("toolbox-gallery");
    ok(await gallery.getByTestId("capability-shelf").count() === 7 && await gallery.getByTestId("capability-card").count() === 36, "Toolbox renders seven reference shelves and the Connected apps adapter");
    await gallery.getByRole("button", { name: "Next: Work with data", exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-testid="capability-strip"]')?.scrollLeft > 0);
    ok(true, "capability shelves scroll with their arrow buttons");
    await gallery.getByLabel("Search capabilities", { exact: true }).fill("Calculations");
    ok(await gallery.getByTestId("capability-card").count() === 1, "Toolbox search filters names and descriptions");
    await gallery.getByRole("button", { name: "Calculations settings", exact: true }).click();
    const unavailable = page.getByRole("dialog", { name: "Calculations settings", exact: true });
    ok(await unavailable.getByRole("switch").isDisabled() && await unavailable.getByText("This capability is not available in BotTeam yet.", { exact: true }).isVisible(), "unsupported capabilities are clearly unavailable and cannot grant fake tools");
    await unavailable.getByRole("button", { name: "Close capability settings", exact: true }).click();
    await gallery.getByLabel("Search capabilities", { exact: true }).fill("");
    await gallery.getByRole("button", { name: "Memory settings", exact: true }).click();
    const memoryPanel = page.getByRole("dialog", { name: "Memory settings", exact: true });
    await memoryPanel.waitFor();
    await memoryPanel.getByRole("tab", { name: "Notes", exact: true }).click();
    ok(await memoryPanel.isVisible(), "Memory opens its resource settings in a right-side panel");
    await memoryPanel.getByRole("button", { name: "Close capability settings", exact: true }).focus();
    await page.keyboard.press("Shift+Tab");
    ok(await memoryPanel.getByRole("button", { name: "Done", exact: true }).evaluate((el) => document.activeElement === el), "capability panel traps keyboard focus");
    await memoryPanel.getByRole("button", { name: "Close capability settings", exact: true }).click();
    ok(await gallery.getByRole("button", { name: "Memory settings", exact: true }).evaluate((el) => document.activeElement === el), "closing capability settings restores focus to the card");
    for (const width of [360, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Toolbox shelves fit ${width}px without page overflow`);
      await gallery.getByRole("button", { name: "Memory settings", exact: true }).click();
      ok((await memoryPanel.locator("aside").boundingBox()).width <= width, `capability settings fit ${width}px`);
      await memoryPanel.getByRole("button", { name: "Close capability settings", exact: true }).click();
    }
    await page.setViewportSize({ width: 1500, height: 900 });
    await gallery.getByLabel("Search capabilities", { exact: true }).fill("Skills");
    await gallery.getByRole("button", { name: "Skills settings", exact: true }).click();
    const skillsPanel = page.getByRole("dialog", { name: "Skills settings", exact: true });
    await skillsPanel.getByTestId("new-skill").click();
    await page.getByTestId("skill-editor").waitFor();
    await page.getByTestId("skill-editor").getByRole("textbox", { name: "Name", exact: true }).focus();
    await page.keyboard.press("Escape");
    ok(await page.getByTestId("skill-editor").count() === 0 && await skillsPanel.isVisible(), "Escape closes the nested skill editor while keeping capability settings open");
    await skillsPanel.getByRole("button", { name: "Close capability settings", exact: true }).click();
    await gallery.getByLabel("Search capabilities", { exact: true }).fill("");
    await editor.getByRole("switch", { name: "memory enabled", exact: true }).click();
    ok((await json("/api/bots")).bots.find((b) => b.id === id).memory !== false, "Memory assignment remains a draft until Save");
    await editor.locator("header").getByRole("button", { name: "Save", exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[role="status"]')?.textContent === "Saved");
    const configured = (await json("/api/bots")).bots.find((b) => b.id === id);
    ok(configured.memory === false && configured.approvalMode === "edits", "Save persists Memory and the changed approval policy");
    // Open chat and exercise the configured agent with the real Echo runtime.
    await editor.getByRole("button", { name: "Open in chat", exact: true }).click();
    const composer = page.getByLabel(`Message ${name} saved`);
    await composer.fill("phase nine smoke test"); await composer.press("Enter");
    await page.getByText("You said: phase nine smoke test", { exact: true }).waitFor({ timeout: 15000 });
    ok(true, "saved Agent configuration works in a real Echo conversation");
    await page.getByTestId("nav-agents").click();
    await page.getByLabel("Search agents").fill(name);
    ok(await page.getByTestId("agent-card").count() === 1, "search finds the created Agent");
    await page.getByTestId("agent-card").getByRole("button", { name: `Edit agent: ${name} saved`, exact: true }).click();
    await editor.getByRole("button", { name: `Agent actions: ${name} saved`, exact: true }).click();
    await page.getByRole("menuitem", { name: "Duplicate", exact: true }).click();
    await page.waitForFunction((id) => location.hash.split("/")[2] !== id, id);
    const copyId = await page.evaluate(() => location.hash.split("/")[2]); made.push(copyId);
    const copyName = await editor.getByLabel("Name", { exact: true }).inputValue();
    ok(copyName === name + " saved copy", "Duplicate opens the new Agent editor");
    await editor.getByRole("button", { name: `Agent actions: ${copyName}` }).click();
    await page.getByRole("menuitem", { name: "Archive", exact: true }).click();
    await page.getByRole("dialog", { name: "Archive agent", exact: true }).getByRole("button", { name: "Archive", exact: true }).click();
    await page.getByTestId("nav-agents").click(); await page.getByLabel("Search agents").fill(name); await page.getByLabel("Status", { exact: true }).selectOption("archived");
    const card = page.getByTestId("agent-card").filter({ hasText: copyName }); await card.waitFor();
    ok(await card.count() === 1, "Archived filter includes the archived copy");
    await card.getByRole("button", { name: `Agent actions: ${copyName}` }).click(); await page.getByRole("menuitem", { name: "Restore", exact: true }).click(); await page.getByRole("dialog", { name: "Restore agent", exact: true }).getByRole("button", { name: "Restore", exact: true }).click();
    await page.getByLabel("Status", { exact: true }).selectOption("active"); await card.waitFor();
    ok(true, "Restore returns the Agent to the active filter");
    await card.getByRole("button", { name: `Agent actions: ${copyName}` }).click(); await page.getByRole("menuitem", { name: "Delete permanently", exact: true }).click();
    const deletion = page.getByRole("dialog", { name: "Delete permanently", exact: true });
    ok(await deletion.getByRole("button", { name: "Delete", exact: true }).isDisabled(), "delete requires the exact Agent name");
    await deletion.getByRole("textbox").fill(copyName); await deletion.getByRole("button", { name: "Delete", exact: true }).click();
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    ok((await json("/api/bots")).bots.some((b) => b.id === copyId), "Delete supports Undo");
    await page.getByRole("button", { name: "Agent templates", exact: true }).click();
    const library = page.getByRole("dialog", { name: "Agent templates", exact: true }); await library.getByRole("button", { name: "Use template", exact: true }).first().waitFor();
    await library.getByLabel("Industry", { exact: true }).selectOption("software");
    await library.getByRole("button", { name: "Preview", exact: true }).first().click();
    await library.getByRole("button", { name: "Use template", exact: true }).click(); await editor.waitFor();
    const templateId = await page.evaluate(() => location.hash.split("/")[2]); made.push(templateId);
    ok((await editor.getByLabel("Instructions", { exact: true }).inputValue()).length > 100, "template installs offline and opens an editor with instructions");
    for (const width of [360, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 900 }); ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `editor fits ${width}px`);
      await editor.locator("nav").getByRole("button", { name: "Agents", exact: true }).click();
      await page.getByTestId("page-agents").waitFor();
      ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Agent list fits ${width}px`);
      await page.keyboard.press("n"); await dialog.waitFor();
      ok((await dialog.locator("form").boundingBox()).width <= width, `New agent dialog fits ${width}px`);
      await page.keyboard.press("Escape");
      await page.evaluate((id) => { location.hash = `#/agents/${id}/build`; }, templateId); await editor.waitFor();
    }
    await page.setViewportSize({ width: 1500, height: 900 });
    await page.evaluate(() => { location.hash = "#/agents/missing/build"; }); await page.getByTestId("page-agents").waitFor(); ok(true, "unknown Agent address returns to the list");
  } finally { for (const id of made) await json(`/api/bots/${id}`, "DELETE").catch(() => {}); }
}
